"""
Manual per-document title-override store.

Personal-corpus escape hatch for exactly one problem: the automatic
resolver (`retrieval_view.resolve_main_text_title`) sometimes lands on a
technically-valid but useless title -- a PDF/DOCX export tool's own default
document-title metadata ("Untitled 1") that isn't caught by
`extractors.clean_title`'s junk-title filter because it doesn't match that
filter's shape (see its regex: "Untitled 1" has a space before the digit,
"Untitled1"/"Untitled" alone do not). This is a UI/metadata correction, not
a second parser or a source-file rename: it never touches the source file,
never bypasses extraction/validation, and never invents a new document
model -- it just seeds one extra candidate that
`DocumentPipeline._prepare_for_profile` (pipeline.py) checks before falling
through to the existing resolution chain, so every downstream reader of the
resolved title (H1 synthesis, chunk header paths, index metadata, citation
labels) sees one single corrected value, the same way they already agree on
whatever the automatic resolver would have produced.

Persisted as a single small JSON sidecar next to the per-document index
files this pipeline already writes (`docs/.index/title_overrides.json`,
next to `docs/.index/<document_id>.json` -- index_schema.py) -- the
smallest addition to the existing per-document JSON persistence tier,
rather than a new database, a new per-document file, or a config field.
Keyed by the same stable `document_id` (`pipeline.stable_document_id`)
every index entry already uses, so an override survives a browser refresh,
a service restart, and reprocessing/reconversion of that same source
(nothing here is deleted or regenerated by re-running the pipeline; the
caller is responsible for re-running `DocumentPipeline.index()` after a
set/clear so the index/Markdown/chunks stay in sync with the override --
see pipeline.py's `set_title_override`/`clear_title_override`).
"""
from __future__ import annotations

import json
import os
from typing import Dict, Optional

_OVERRIDES_FILENAME = "title_overrides.json"
# A `_meta` subdirectory, not `index_dir` itself: every top-level `*.json`
# file directly in `index_dir` is assumed, elsewhere in this codebase
# (orchestrator.py's DocStore.reload(), eval_retrieval.py), to be a
# versioned per-document index payload (index_schema.py) -- a sidecar file
# living alongside them would be picked up by that same glob, fail
# `is_legacy_schema()` (no `schema_version` key), and get counted/reported
# as a corrupt/legacy index file needing a `cli.py rebuild`. Nesting it one
# level down keeps it out of that glob's match set entirely while still
# living under the same per-document JSON persistence tier (docs/.index).
_OVERRIDES_SUBDIR = "_meta"


def _overrides_path(index_dir: str) -> str:
    return os.path.join(index_dir, _OVERRIDES_SUBDIR, _OVERRIDES_FILENAME)


def load_title_overrides(index_dir: str) -> Dict[str, str]:
    """Returns the full `{document_id: title}` override map. Never raises --
    a missing, empty, or corrupt sidecar file is treated as "no overrides
    recorded" (the same fail-open-to-automatic-resolution posture as any
    other optional per-document metadata in this pipeline)."""
    path = _overrides_path(index_dir)
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(data, dict):
        return {}
    return {k: v for k, v in data.items() if isinstance(v, str) and v.strip()}


def _save_title_overrides(index_dir: str, overrides: Dict[str, str]) -> None:
    # Same atomic-write pattern as index_schema.write_index_atomic: write to
    # a temp file in the same directory, then os.replace() into place, so a
    # crash mid-write can never leave a half-written/corrupt override file.
    path = _overrides_path(index_dir)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp_path = path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(overrides, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp_path, path)


def get_title_override(index_dir: str, document_id: str) -> Optional[str]:
    """The manually-set title for `document_id`, or None if it has none
    (falls back to normal automatic title resolution)."""
    return load_title_overrides(index_dir).get(document_id)


def set_title_override(index_dir: str, document_id: str, title: str) -> str:
    """Records `title` as `document_id`'s manual override. Returns the
    stored (whitespace-trimmed) title. Does not itself touch the source
    file, the index, or any Markdown -- the caller must re-run
    `DocumentPipeline.index(..., force=True)` for the change to reach
    MAIN_TEXT/chunks/citations (see pipeline.py's `set_title_override`)."""
    title = (title or "").strip()
    if not title:
        raise ValueError("title override must be a non-empty string")
    overrides = load_title_overrides(index_dir)
    overrides[document_id] = title
    _save_title_overrides(index_dir, overrides)
    return title


def clear_title_override(index_dir: str, document_id: str) -> bool:
    """Removes `document_id`'s manual override, if any. Returns True if an
    override was actually present and removed. Does not itself trigger
    reprocessing -- see pipeline.py's `clear_title_override`."""
    overrides = load_title_overrides(index_dir)
    if document_id not in overrides:
        return False
    del overrides[document_id]
    _save_title_overrides(index_dir, overrides)
    return True
